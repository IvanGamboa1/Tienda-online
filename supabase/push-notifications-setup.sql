create or replace function public.notify_k1ko_new_order()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  project_url text;
  webhook_secret text;
begin
  select decrypted_secret into project_url
  from vault.decrypted_secrets
  where name = 'k1ko_push_project_url';

  select decrypted_secret into webhook_secret
  from vault.decrypted_secrets
  where name = 'k1ko_push_webhook_secret';

  if project_url is null or webhook_secret is null then
    raise warning 'Notificaciones K1KO no enviadas: faltan secretos de Vault.';
    return new;
  end if;

  perform net.http_post(
    url := project_url || '/functions/v1/push-new-order',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-push-webhook-secret', webhook_secret
    ),
    body := jsonb_build_object(
      'type', tg_op,
      'table', tg_table_name,
      'schema', tg_table_schema,
      'record', to_jsonb(new),
      'old_record', null
    ),
    timeout_milliseconds := 5000
  );

  return new;
exception
  when others then
    raise warning 'No se pudo encolar la notificación push K1KO: %', sqlerrm;
    return new;
end;
$$;

drop trigger if exists notify_k1ko_new_order on public.orders;
create trigger notify_k1ko_new_order
after insert on public.orders
for each row
execute function public.notify_k1ko_new_order();
